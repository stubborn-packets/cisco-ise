def output_key(name: str) -> str:
    """Stable map key derived only from the YAML name.

    Drop the prefix, replace - with _. NDG uses the existing label
    helper (drop the ndg_ prefix). No lab-specific abbreviations.
    """
    if "#" in name:
        # NDG ISE form. Re-use the label that the call already uses.
        return _ndg_label(name)[4:]  # "ndg_business_unit_lab" → "business_unit_lab"
    for prefix in ADDRESS:
        if name.startswith(prefix):
            rest = name[len(prefix):].replace("-", "_")
            if not rest:
                raise ReaderError(f"{name} has an empty token after {prefix}")
            return rest
    raise ReaderError(f"{name} has no known prefix for an output key")

