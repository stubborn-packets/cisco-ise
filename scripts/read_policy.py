AP_BOOLS = tuple(k for k in AP_DEFAULTS if k != "allow_5g")


def load_allowed_protocols(root: Path) -> list[dict[str, Any]]:
    path = root / READS[2]
    if not path.is_file():
        raise ReaderError(f"{READS[2]} is missing")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(doc, dict):
        raise ReaderError(f"{READS[2]} is not a mapping")
    rows = doc.get("allowed_protocols")
    if not isinstance(rows, list):
        raise ReaderError("allowed_protocols must be a list")
    return rows


def validate_allowed_protocol(obj: dict[str, Any], index: int) -> None:
    name = obj.get("name")
    if not isinstance(name, str) or not name.startswith("AP-"):
        raise ReaderError(f"allowed protocol {index} name must be AP- + kebab-case")
    if name == "Default Network Access":
        raise ReaderError("Default Network Access is not managed")
    if obj.get("state") not in ("enabled", "disabled"):
        raise ReaderError(f"{name} state must be enabled or disabled")
    description = obj.get("description", "")
    if not isinstance(description, str):
        raise ReaderError(f"{name} description must be a string")
    if "<" in description or ">" in description:
        raise ReaderError(f"{name} description must not contain < or >")
    for field in AP_BOOLS:
        value = obj.get(field, AP_DEFAULTS[field])
        if not isinstance(value, bool):
            raise ReaderError(f"{name} {field} must be a bool")
    allow_5g = obj.get("allow_5g", False)
    if not isinstance(allow_5g, bool):
        raise ReaderError(f"{name} allow_5g must be a bool")
    if obj.get("allow_eap_tls"):
        for field in AP_EAP_TLS_INNER:
            if not isinstance(obj.get(field), bool):
                raise ReaderError(f"{name} needs {field} when allow_eap_tls is true")
    if obj.get("allow_peap"):
        for field in AP_PEAP_INNER:
            value = obj.get(field)
            if field == "peap_allow_peap_eap_ms_chap_v2_pwd_change_retries":
                if not isinstance(value, int) or not 0 <= value <= 3:
                    raise ReaderError(f"{name} {field} must be an int 0-3")
            elif not isinstance(value, bool):
                raise ReaderError(f"{name} needs {field} when allow_peap is true")
    if obj.get("allow_teap"):
        for field in AP_TEAP_INNER:
            if not isinstance(obj.get(field), bool):
                raise ReaderError(f"{name} needs {field} when allow_teap is true")


def _hcl_bool(value: bool) -> str:
    return "true" if value else "false"


def _emit_ap_line(field: str, value: Any) -> str:
    rendered = _hcl_bool(value) if isinstance(value, bool) else str(value)
    return f"  {field} = {rendered}"


def render_allowed_protocol(obj: dict[str, Any]) -> str:
    name = obj["name"]
    label = module_label(name)
    description = obj.get("description") or ""
    lines = [
        f'module "{label}" {{',
        '  source = "../../terraform/modules/allowed-protocols"',
        "",
        f"  name        = {_hcl_string(name)}",
        f"  description = {_hcl_string(description)}",
    ]
    for field in (
        "process_host_lookup",
        "allow_pap_ascii",
        "allow_eap_tls",
        "allow_peap",
        "allow_teap",
    ):
        if obj.get(field, AP_DEFAULTS[field]) is not AP_DEFAULTS[field]:
            lines.append(_emit_ap_line(field, obj[field]))
    lines.append(f"  allow_5g    = {_hcl_bool(obj.get('allow_5g', False))}")
    if obj.get("allow_eap_tls"):
        lines.append("")
        for field in AP_EAP_TLS_INNER:
            lines.append(_emit_ap_line(field, obj[field]))
    if obj.get("allow_peap"):
        lines.append("")
        for field in AP_PEAP_INNER:
            lines.append(_emit_ap_line(field, obj[field]))
    if obj.get("allow_teap"):
        lines.append("")
        for field in AP_TEAP_INNER:
            lines.append(_emit_ap_line(field, obj[field]))
    lines.append("}")
    return "\n".join(lines)


def render_allowed_protocols(rows: list[dict[str, Any]]) -> str:
    for index, obj in enumerate(rows):
        if not isinstance(obj, dict):
            raise ReaderError(f"allowed protocol {index} is not a mapping")
        validate_allowed_protocol(obj, index)
    blocks = [render_allowed_protocol(obj) for obj in rows]
    if not blocks:
        raise ReaderError("no allowed protocols to emit")
    return AP_HEADER + "\n" + "\n\n".join(blocks) + "\n"


def write_policy_sets(root: Path) -> Path:
    text = render(load_policy_sets(root))
    path = root / WRITES[0]
    path.write_text(text, encoding="utf-8")
    return path


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Emit lab policy-set shells, rules, conditions, and allowed protocols from policy/."
    )
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument("--stdout", action="store_true", help="Print the file. Do not write it.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = args.root.resolve()
    try:
        sets = load_policy_sets(root)
        shells = render(sets)
        authn = render_authn(sets)
        authz = render_authz(sets)
        conditions = load_conditions(root)
        cnd_text = render_conditions(conditions)
        protocols = load_allowed_protocols(root)
        ap_text = render_allowed_protocols(protocols)
    except ReaderError as exc:
        print(f"read_policy: {exc}", file=sys.stderr)
        return 1
    if args.stdout:
        sys.stdout.write(shells)
        sys.stdout.write("\n")
        sys.stdout.write(authn)
        sys.stdout.write("\n")
        sys.stdout.write(authz)
        sys.stdout.write("\n")
        sys.stdout.write(cnd_text)
        sys.stdout.write("\n")
        sys.stdout.write(ap_text)
        return 0
    written = []
    for rel, text in (
        (WRITES[0], shells),
        (WRITES[1], authn),
        (WRITES[2], authz),
        (WRITES[3], cnd_text),
        (WRITES[4], ap_text),
    ):
        path = root / rel
        path.write_text(text, encoding="utf-8")
        written.append(rel)
    print("read_policy: wrote")
    for rel in written:
        print(f"- {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
