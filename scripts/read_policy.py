def validate_allowed_protocol(obj: dict[str, Any], index: int) -> None:
    name = obj.get("name")
    if not isinstance(name, str) or not name.startswith("AP-"):
        raise ReaderError(f"allowed protocol {index} name must be AP- + kebab-case")
    if name == "Default Network Access":
        raise ReaderError("Default Network Access is not managed")
    if obj.get("state") not in ("enabled", "disabled"):
        raise ReaderError(f"{name} state must be enabled or disabled")
    description = obj.get("description", "")
    if not isinstance(description, str):
        raise ReaderError(f"{name} description must be a string")
    if "<" in description or ">" in description:
        raise ReaderError(f"{name} description must not contain < or >")
    for field in AP_BOOLS:
        value = obj.get(field, AP_DEFAULTS[field])
        if not isinstance(value, bool):
            raise ReaderError(f"{name} {field} must be a bool")
    allow_5g = obj.get("allow_5g", False)
    if not isinstance(allow_5g, bool):
        raise ReaderError(f"{name} allow_5g must be a bool")
    if obj.get("allow_eap_tls"):
        for field in AP_EAP_TLS_INNER:
            if not isinstance(obj.get(field), bool):
                raise ReaderError(f"{name} needs {field} when allow_eap_tls is true")
    if obj.get("allow_peap"):
        for field in AP_PEAP_INNER:
            value = obj.get(field)
            if field == "peap_allow_peap_eap_ms_chap_v2_pwd_change_retries":
                if not isinstance(value, int) or not 0 <= value <= 3:
                    raise ReaderError(f"{name} {field} must be an int 0-3")
            elif not isinstance(value, bool):
                raise ReaderError(f"{name} needs {field} when allow_peap is true")
    if obj.get("allow_teap"):
        for field in AP_TEAP_INNER:
            if not isinstance(obj.get(field), bool):
                raise ReaderError(f"{name} needs {field} when allow_teap is true")


def _hcl_bool(value: bool) -> str:
    return "true" if value else "false"


def _emit_ap_line(field: str, value: Any) -> str:
    rendered = _hcl_bool(value) if isinstance(value, bool) else str(value)
    return f"  {field} = {rendered}"


