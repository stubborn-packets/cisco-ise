# Locked roots. A sixth root is a module + linter + docs change, not a YAML-only change.
NDG_CUSTOM_ROOTS = ("BusinessUnit", "Stage", "Function")
NDG_BUILTIN_ROOTS = ("Location", "Device Type")


def load_ndg_roots(root: Path) -> list[dict[str, Any]]:
    path = root / "policy/ndg.yaml"
    if not path.is_file():
        raise ReaderError("policy/ndg.yaml is missing")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(doc, dict):
        raise ReaderError("policy/ndg.yaml is not a mapping")
    roots = doc.get("roots")
    if not isinstance(roots, list):
        raise ReaderError("roots must be a list")
    return roots


def _ndg_label(name: str) -> str:
    """Stable label. Existing nine must not move.

    BusinessUnit#BusinessUnit          → ndg_business_unit
    Location#All Locations#USA         → ndg_location_usa
    Device Type#All Device Types#switch → ndg_device_type_switch
    BusinessUnit#BusinessUnit#lab      → ndg_business_unit_lab
    """
    # Known roots → the token already used in live addresses.
    root_token = {
        "BusinessUnit": "business_unit",
        "Stage": "stage",
        "Function": "function",
        "Location": "location",
        "Device Type": "device_type",
    }
    parts = name.split("#")
    if len(parts) == 2:
        token = root_token.get(parts[0])
        if token is None:
            raise ReaderError(f"{name} root has no label token")
        return f"ndg_{token}"
    if len(parts) == 3:
        root = root_token.get(parts[0])
        if root is None:
            raise ReaderError(f"{name} root has no label token")
        value = parts[2].replace("-", "_").lower()
        return f"ndg_{root}_{value}"
    raise ReaderError(f"{name} is not a type#type or type#container#value name")


def derive_ndg_objects(roots: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Return the objects to emit. Containers first, then leaves.

    A new allowed value becomes a new leaf. A new root is not handled here.
    """
    objects: list[dict[str, Any]] = []
    seen_roots: set[str] = set()
    for row in roots:
        if not isinstance(row, dict):
            raise ReaderError("ndg root is not a mapping")
        ise_root = row.get("ise_root")
        if ise_root not in NDG_CUSTOM_ROOTS + NDG_BUILTIN_ROOTS:
            raise ReaderError(f"{ise_root} is not a locked root")
        if ise_root in seen_roots:
            raise ReaderError(f"{ise_root} appears twice")
        seen_roots.add(ise_root)
        allowed = row.get("allowed_values") or []
        if not isinstance(allowed, list):
            raise ReaderError(f"{ise_root} allowed_values must be a list")
        # Custom roots get a type#type container. Built-ins do not.
        if ise_root in NDG_CUSTOM_ROOTS:
            container = f"{ise_root}#{ise_root}"
            objects.append({
                "name": container,
                "root_group": ise_root,
                "is_root": True,
                "description": f"Custom NDG type container for lab {ise_root} leaves.",
                "label": _ndg_label(container),
            })
            container_token = ise_root
        else:
            # Built-in: Location → All Locations, Device Type → All Device Types
            container_token = "All Locations" if ise_root == "Location" else "All Device Types"
        for value in allowed:
            if not isinstance(value, str) or not value:
                raise ReaderError(f"{ise_root} allowed value must be a non-empty string")
            leaf = f"{ise_root}#{container_token}#{value}"
            objects.append({
                "name": leaf,
                "root_group": ise_root,
                "is_root": False,
                "description": f"Lab {ise_root} leaf.",
                "label": _ndg_label(leaf),
                "depends_on_container": ise_root in NDG_CUSTOM_ROOTS,
            })
    return objects


def render_ndg(obj: dict[str, Any]) -> str:
    name = obj["name"]
    label = obj["label"]
    description = obj.get("description") or ""
    lines = [
        f'module "{label}" {{',
        '  source = "../../terraform/modules/ndg"',
        "",
        f"  name        = {_hcl_string(name)}",
        f"  root_group  = {_hcl_string(obj['root_group'])}",
    ]
    if obj.get("is_root"):
        lines.append("  is_root     = true")
    if description:
        lines.append(f"  description = {_hcl_string(description)}")
    # Custom leaves wait for their type container. Built-in leaves do not.
    if obj.get("depends_on_container"):
        container_label = _ndg_label(f"{obj['root_group']}#{obj['root_group']}")
        lines.append("")
        lines.append(f"  depends_on = [module.{container_label}]")
    lines.append("}")
    return "\n".join(lines)


def render_ndgs(roots: list[dict[str, Any]]) -> str:
    objects = derive_ndg_objects(roots)
    if not objects:
        raise ReaderError("no NDG objects to emit")
    blocks = [render_ndg(obj) for obj in objects]
    return NDG_HEADER + "\n" + "\n\n".join(blocks) + "\n"


