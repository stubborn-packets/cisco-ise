CND_HEADER = """\
# Generated by scripts/read_policy.py. Do not hand-edit.
# Source: policy/conditions.yaml. Review surface stays that file.
# Attribute conditions omit condition_type (module default LibraryConditionAttributes).
# AND/OR blocks set condition_type and pass children as ConditionAttributes.
# No for_each. Addresses match the live lab state.
# Ids stay in state, not in policy/.
"""


def load_conditions(root: Path) -> list[dict[str, Any]]:
    path = root / "policy/conditions.yaml"
    if not path.is_file():
        raise ReaderError("policy/conditions.yaml is missing")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(doc, dict):
        raise ReaderError("policy/conditions.yaml is not a mapping")
    conditions = doc.get("conditions")
    if not isinstance(conditions, list):
        raise ReaderError("conditions must be a list")
    return conditions


def validate_condition(obj: dict[str, Any], index: int) -> None:
    name = obj.get("name")
    if not isinstance(name, str) or not name.startswith("CND-"):
        raise ReaderError(f"condition {index} name must be CND- + kebab-case")
    if obj.get("state") not in ("enabled", "disabled"):
        raise ReaderError(f"{name} state must be enabled or disabled")
    description = obj.get("description", "")
    if not isinstance(description, str):
        raise ReaderError(f"{name} description must be a string")
    if "<" in description or ">" in description:
        raise ReaderError(f"{name} description must not contain < or >")
    ctype = obj.get("type", "LibraryConditionAttributes")
    if ctype not in ("LibraryConditionAttributes", "LibraryConditionAndBlock", "LibraryConditionOrBlock"):
        raise ReaderError(f"{name} type must be LibraryConditionAttributes, LibraryConditionAndBlock, or LibraryConditionOrBlock")
    if ctype == "LibraryConditionAttributes":
        for field in ("dictionary_name", "attribute_name", "operator", "attribute_value"):
            if not isinstance(obj.get(field), str) or not obj.get(field):
                raise ReaderError(f"{name} attribute condition needs {field}")
        if obj.get("children"):
            raise ReaderError(f"{name} attribute condition must not have children")
    else:
        children = obj.get("children")
        if not isinstance(children, list) or len(children) < 2:
            raise ReaderError(f"{name} AND/OR block needs at least two children")
        for child in children:
            if not isinstance(child, dict):
                raise ReaderError(f"{name} child is not a mapping")
            if child.get("type") != "ConditionAttributes":
                raise ReaderError(f"{name} child type must be ConditionAttributes")
            for field in ("dictionary_name", "attribute_name", "operator", "attribute_value"):
                if not isinstance(child.get(field), str) or not child.get(field):
                    raise ReaderError(f"{name} child needs {field}")


def _render_child(child: dict[str, Any]) -> str:
    return "\n".join([
        "    {",
        '      condition_type  = "ConditionAttributes"',
        f"      dictionary_name = {_hcl_string(child['dictionary_name'])}",
        f"      attribute_name  = {_hcl_string(child['attribute_name'])}",
        f"      operator        = {_hcl_string(child['operator'])}",
        f"      attribute_value = {_hcl_string(child['attribute_value'])}",
        "    },",
    ])


def render_condition(obj: dict[str, Any]) -> str:
    name = obj["name"]
    label = module_label(name)
    description = obj.get("description") or ""
    ctype = obj.get("type", "LibraryConditionAttributes")
    lines = [
        f'module "{label}" {{',
        '  source = "../../terraform/modules/condition"',
        "",
        f"  name        = {_hcl_string(name)}",
        f"  description = {_hcl_string(description)}",
    ]
    if ctype != "LibraryConditionAttributes":
        lines.append(f"  condition_type = {_hcl_string(ctype)}")
        lines.append("")
        lines.append("  children = [")
        for child in obj["children"]:
            lines.append(_render_child(child))
        lines.append("  ]")
    else:
        lines.append(f"  dictionary_name = {_hcl_string(obj['dictionary_name'])}")
        lines.append(f"  attribute_name  = {_hcl_string(obj['attribute_name'])}")
        lines.append(f"  operator        = {_hcl_string(obj['operator'])}")
        lines.append(f"  attribute_value = {_hcl_string(obj['attribute_value'])}")
    lines.append("}")
    return "\n".join(lines)


def render_conditions(conditions: list[dict[str, Any]]) -> str:
    for index, obj in enumerate(conditions):
        if not isinstance(obj, dict):
            raise ReaderError(f"condition {index} is not a mapping")
        validate_condition(obj, index)
    blocks = [render_condition(obj) for obj in conditions]
    if not blocks:
        raise ReaderError("no conditions to emit")
    return CND_HEADER + "\n" + "\n\n".join(blocks) + "\n"


def write_policy_sets(root: Path) -> Path:
    text = render(load_policy_sets(root))
    path = root / WRITES[0]
    path.write_text(text, encoding="utf-8")
    return path


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Emit lab policy-set shells and rules from policy/."
    )
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument("--stdout", action="store_true", help="Print the file. Do not write it.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = args.root.resolve()
    try:
        sets = load_policy_sets(root)
        shells = render(sets)
        authn = render_authn(sets)
        authz = render_authz(sets)
        conditions = load_conditions(root)
        cnd_text = render_conditions(conditions)
    except ReaderError as exc:
        print(f"read_policy: {exc}", file=sys.stderr)
        return 1
    if args.stdout:
        sys.stdout.write(shells)
        sys.stdout.write("\n")
        sys.stdout.write(authn)
        sys.stdout.write("\n")
        sys.stdout.write(authz)
        sys.stdout.write("\n")
        sys.stdout.write(cnd_text)
        return 0
    written = []
    for rel, text in (
        (WRITES[0], shells),
        (WRITES[1], authn),
        (WRITES[2], authz),
        (WRITES[3], cnd_text),
    ):
        path = root / rel
        path.write_text(text, encoding="utf-8")
        written.append(rel)
    print("read_policy: wrote")
    for rel in written:
        print(f"- {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
