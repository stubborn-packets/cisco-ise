"""Reader. No ISE.

Reads policy/policy-sets.yaml, policy/conditions.yaml, and
policy/allowed-protocols.yaml and emits the lab calls. Thin modules stay.
Ids stay out of policy/. Band is not sent. Sets stay disabled. Rules may
be enabled. profiles is a name, not an id. No security_group. Conditions
may be attribute or AND/OR. Allowed protocols stay the existing AP- names.
Default Network Access is not managed.

Other families stay hand-copied.
"""

