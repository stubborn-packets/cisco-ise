class ReaderError(ValueError):
    pass


def module_label(name: str) -> str:
    for prefix, stem in ADDRESS.items():
        if name.startswith(prefix):
            rest = name[len(prefix) :].replace("-", "_")
            if not rest:
                raise ReaderError(f"{name} has an empty token after {prefix}")
            return stem + rest
    raise ReaderError(f"{name} has no known prefix")


def _hcl_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_policy_sets(root: Path) -> list[dict[str, Any]]:
    path = root / READS[0]
    if not path.is_file():
        raise ReaderError(f"{READS[0]} is missing")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(doc, dict):
        raise ReaderError(f"{READS[0]} is not a mapping")
    sets = doc.get("policy_sets")
    if not isinstance(sets, list):
        raise ReaderError("policy_sets must be a list")
    return sets


def _reject_unwritten(name: str) -> None:
    if name == "Default" or name == "PS-it" or name.startswith("PS-it-"):
        raise ReaderError(f"{name} is not written")
    if name.endswith("-vpn") and not name.startswith("PS-global-"):
        raise ReaderError(f"{name} is a business-unit VPN set and is not written")
    if name.endswith("-wireless") and not name.startswith("PS-global-"):
        raise ReaderError(f"{name} is a business-unit wireless set and is not written")


def validate_set(obj: dict[str, Any], index: int) -> None:
    name = obj.get("name")
    if not isinstance(name, str) or not name.startswith("PS-"):
        raise ReaderError(f"set {index} name must be PS- + kebab-case")
    _reject_unwritten(name)
    rank = obj.get("rank")
    if not isinstance(rank, int) or rank < 0 or rank == 99:
        raise ReaderError(f"{name} rank must be a packed index, not {rank!r}")
    if obj.get("state") != "disabled":
        raise ReaderError(f"{name} must stay disabled")
    service = obj.get("service")
    if not isinstance(service, str) or not service.startswith("AP-"):
        raise ReaderError(f"{name} service must be an AP- name")
    if service == "Default Network Access":
        raise ReaderError(f"{name} must not use Default Network Access")
    condition = obj.get("condition")
    if not isinstance(condition, str) or not condition.startswith("CND-"):
        raise ReaderError(f"{name} condition must be a CND- name")
    description = obj.get("description", "")
    if not isinstance(description, str):
        raise ReaderError(f"{name} description must be a string")
    if "<" in description or ">" in description:
        raise ReaderError(f"{name} description must not contain < or >")


def render_set(obj: dict[str, Any], previous: str | None) -> str:
    name = obj["name"]
    label = module_label(name)
    service = module_label(obj["service"])
    condition = module_label(obj["condition"])
    depends = [f"module.{service}", f"module.{condition}"]
    if previous:
        depends.append(f"module.{previous}")
    depends_txt = ", ".join(depends)
    description = obj.get("description") or ""
    lines = [
        f'module "{label}" {{',
        '  source = "../../terraform/modules/policy-set"',
        "",
        f"  name                = {_hcl_string(name)}",
        f"  description         = {_hcl_string(description)}",
        f"  rank                = {obj['rank']}",
        f"  state               = {_hcl_string(obj['state'])}",
        f"  service_name        = module.{service}.name",
        "  is_proxy            = false",
        f"  condition_id        = module.{condition}.id",
        "  condition_is_negate = false",
        "",
        f"  depends_on = [{depends_txt}]",
        "}",
    ]
    return "\n".join(lines)


def render(sets: list[dict[str, Any]]) -> str:
    ordered = sorted(sets, key=lambda obj: obj["rank"])
    for index, obj in enumerate(ordered):
        validate_set(obj, index)
    ranks = [obj["rank"] for obj in ordered]
    if ranks != list(range(len(ranks))):
        raise ReaderError(f"ranks must be packed 0..{len(ranks) - 1}, got {ranks}")
    blocks = []
    previous: str | None = None
    for obj in ordered:
        blocks.append(render_set(obj, previous))
        previous = module_label(obj["name"])
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def validate_authn(rule: dict[str, Any], parent: str) -> None:
    name = rule.get("name")
    if not isinstance(name, str) or not name.startswith("AN-") or name == "Default":
        raise ReaderError(f"{parent} authentication rule name must be AN- + kebab-case")
    rank = rule.get("rank")
    if not isinstance(rank, int) or rank < 0 or rank == 99:
        raise ReaderError(f"{name} rank must be an integer from 0 to 98")
    if rule.get("state") not in ("enabled", "disabled", "monitor"):
        raise ReaderError(f"{name} state must be enabled, disabled, or monitor")
    condition = rule.get("condition")
    if not isinstance(condition, str) or not condition.startswith("CND-"):
        raise ReaderError(f"{name} condition must be a CND- name")
    identity = rule.get("identity_source")
    if identity not in IDENTITY_SOURCES:
        raise ReaderError(f"{name} identity_source must be Internal Users or Internal Endpoints")
    for field in ("if_auth_fail", "if_process_fail", "if_user_not_found"):
        action = rule.get(field)
        if action not in AUTH_ACTIONS:
            raise ReaderError(f"{name} {field} must be REJECT, DROP, or CONTINUE")


def render_authn_rule(rule: dict[str, Any], parent: str) -> str:
    name = rule["name"]
    label = module_label(name)
    parent_label = module_label(parent)
    condition = module_label(rule["condition"])
    lines = [
        f'module "{label}" {{',
        '  source = "../../terraform/modules/authentication-rule"',
        "",
        f"  name                 = {_hcl_string(name)}",
        f"  policy_set_id        = module.{parent_label}.id",
        f"  rank                 = {rule['rank']}",
        f"  state                = {_hcl_string(rule['state'])}",
        f"  condition_id         = module.{condition}.id",
        "  condition_is_negate  = false",
        f"  identity_source_name = {_hcl_string(rule['identity_source'])}",
        f"  if_auth_fail         = {_hcl_string(rule['if_auth_fail'])}",
        f"  if_process_fail      = {_hcl_string(rule['if_process_fail'])}",
        f"  if_user_not_found    = {_hcl_string(rule['if_user_not_found'])}",
        "",
        f"  depends_on = [module.{parent_label}, module.{condition}]",
        "}",
    ]
    return "\n".join(lines)


def render_authn(sets: list[dict[str, Any]]) -> str:
    ordered = sorted(sets, key=lambda obj: obj["rank"])
    blocks = []
    for obj in ordered:
        parent = obj["name"]
        rules = obj.get("authentication_rules") or []
        if not isinstance(rules, list):
            raise ReaderError(f"{parent} authentication_rules must be a list")
        for rule in sorted(rules, key=lambda item: item.get("rank", 0)):
            if not isinstance(rule, dict):
                raise ReaderError(f"{parent} authentication rule is not a mapping")
            validate_authn(rule, parent)
            blocks.append(render_authn_rule(rule, parent))
    if not blocks:
        raise ReaderError("no authentication rules to emit")
    return AUTH_HEADER + "\n" + "\n\n".join(blocks) + "\n"


