def validate_profile(obj: dict[str, Any], index: int, vlan_map: dict[str, str]) -> None:
    name = obj.get("name")
    if not isinstance(name, str) or not name.startswith("PR-"):
        raise ReaderError(f"profile {index} name must be PR- + kebab-case")
    if name in ("PermitAccess", "DenyAccess"):
        raise ReaderError(f"{name} is a built-in and is not managed")
    if obj.get("state") not in ("enabled", "disabled"):
        raise ReaderError(f"{name} state must be enabled or disabled")
    description = obj.get("description", "")
    if not isinstance(description, str):
        raise ReaderError(f"{name} description must be a string")
    if "<" in description or ">" in description:
        raise ReaderError(f"{name} description must not contain < or >")
    access_type = obj.get("access_type", "ACCESS_ACCEPT")
    if access_type not in ("ACCESS_ACCEPT", "ACCESS_REJECT"):
        raise ReaderError(f"{name} access_type must be ACCESS_ACCEPT or ACCESS_REJECT")
    vlan = obj.get("vlan")
    if vlan is not None:
        if not isinstance(vlan, str) or vlan not in vlan_map:
            raise ReaderError(f"{name} vlan must be a name from inventory/vlans.yaml")
    dacl = obj.get("dacl")
    if dacl is not None:
        if not isinstance(dacl, str) or not dacl.startswith("ACL-"):
            raise ReaderError(f"{name} dacl must be an ACL- name")
    timer = obj.get("reauth_timer")
    if timer is not None:
        if not isinstance(timer, int) or not 1 <= timer <= 65535:
            raise ReaderError(f"{name} reauth_timer must be 1-65535 when set")
        connectivity = obj.get("reauth_connectivity", "DEFAULT")
        if connectivity not in ("DEFAULT", "RADIUS_REQUEST"):
            raise ReaderError(f"{name} reauth_connectivity must be DEFAULT or RADIUS_REQUEST")
    asa = obj.get("asa_vpn")
    if asa is not None and not isinstance(asa, str):
        raise ReaderError(f"{name} asa_vpn must be a string when set")
    if "security_group" in obj or "sgt" in obj:
        raise ReaderError(f"{name} must not set an SGT")


def render_profile(obj: dict[str, Any], vlan_map: dict[str, str]) -> str:
    name = obj["name"]
    label = module_label(name)
    description = obj.get("description") or ""
    access_type = obj.get("access_type", "ACCESS_ACCEPT")
    lines = [
        f'module "{label}" {{',
        '  source = "../../terraform/modules/authorization-profile"',
        "",
        f"  name        = {_hcl_string(name)}",
        f"  description = {_hcl_string(description)}",
        f"  access_type = {_hcl_string(access_type)}",
    ]
    dacl = obj.get("dacl")
    if dacl:
        dacl_label = module_label(dacl)
        lines.append(f"  dacl_name   = module.{dacl_label}.name")
    vlan = obj.get("vlan")
    if vlan:
        lines.append(f"  vlan_name_id = {_hcl_string(vlan_map[vlan])}")
        lines.append("  vlan_tag_id  = 1")
    asa = obj.get("asa_vpn")
    if asa:
        lines.append(f"  asa_vpn                       = {_hcl_string(asa)}")
    timer = obj.get("reauth_timer")
    if timer:
        connectivity = obj.get("reauth_connectivity", "DEFAULT")
        lines.append(f"  reauthentication_timer        = {timer}")
        lines.append(f"  reauthentication_connectivity = {_hcl_string(connectivity)}")
    if dacl:
        dacl_label = module_label(dacl)
        lines.append("")
        lines.append(f"  depends_on = [module.{dacl_label}]")
    lines.append("}")
    return "\n".join(lines)


def render_profiles(rows: list[dict[str, Any]], vlan_map: dict[str, str]) -> str:
    for index, obj in enumerate(rows):
        if not isinstance(obj, dict):
            raise ReaderError(f"profile {index} is not a mapping")
        validate_profile(obj, index, vlan_map)
    blocks = [render_profile(obj, vlan_map) for obj in rows]
    if not blocks:
        raise ReaderError("no authorization profiles to emit")
    return PROFILE_HEADER + "\n" + "\n\n".join(blocks) + "\n"


SGT_HEADER = """\
# Generated by scripts/read_policy.py. Do not hand-edit.
# Source: policy/sgt.yaml. Review surface stays that file.
# SGT_ + snake_case, max 32. YAML name equals the ISE name.
# Bootstrap SGT stays in terraform.tfvars. Do not manage Unknown (tag 0).
# No for_each. Addresses match the live lab state.
# Ids stay in state, not in policy/.
"""

# Known live addresses. A new name would be a new address and orphan state.
SGT_LIVE = {
    "SGT_lab_users": "sgt_lab_users",
    "SGT_lab_devices": "sgt_lab_devices",
}


def load_sgts(root: Path) -> list[dict[str, Any]]:
    path = root / "policy/sgt.yaml"
    if not path.is_file():
        raise ReaderError("policy/sgt.yaml is missing")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(doc, dict):
        raise ReaderError("policy/sgt.yaml is not a mapping")
    rows = doc.get("sgts")
    if not isinstance(rows, list):
        raise ReaderError("sgts must be a list")
    return rows


def validate_sgt(obj: dict[str, Any], index: int) -> None:
    if not isinstance(obj, dict):
        raise ReaderError(f"sgt {index} is not a mapping")
    name = obj.get("name")
    if not isinstance(name, str) or not name:
        raise ReaderError(f"sgt {index} needs a name")
    if name not in SGT_LIVE:
        raise ReaderError(
            f"{name} is not a live SGT address. "
            "Add it to SGT_LIVE only after the object exists in state."
        )
    if not name.startswith("SGT_") or "-" in name or len(name) > 32:
        raise ReaderError(
            f"{name} must be SGT_ + snake_case, max 32. ISE rejects hyphens."
        )
    value = obj.get("value")
    if not isinstance(value, int) or value < 0 or value > 65519:
        raise ReaderError(f"{name} value must be an integer 0 through 65519")
    if value == 0:
        raise ReaderError(f"{name} must not use the built-in Unknown tag 0")
    if name == "SGT_lab_bootstrap":
        raise ReaderError("SGT_lab_bootstrap stays in terraform.tfvars")
    for field in ("description", "owner", "bu", "state"):
        if field in obj and not isinstance(obj[field], str):
            raise ReaderError(f"{name} {field} must be a string when present")
    if "propagate_to_apic" in obj and not isinstance(obj["propagate_to_apic"], bool):
        raise ReaderError(f"{name} propagate_to_apic must be a bool when present")


def render_sgt(obj: dict[str, Any]) -> str:
    name = obj["name"]
    label = SGT_LIVE[name]
    description = obj.get("description") or ""
    lines = [
        f'module "{label}" {{',
        '  source = "../../terraform/modules/sgt"',
        "",
        f"  name              = {_hcl_string(name)}",
        f"  value             = {obj['value']}",
    ]
    if description:
        lines.append(f"  description       = {_hcl_string(description)}")
    # Emit the value that is in the YAML. Module default is false.
    propagate = obj.get("propagate_to_apic", False)
    lines.append(f"  propagate_to_apic = {_hcl_bool(propagate)}")
    lines.append("}")
    return "\n".join(lines)


def render_sgts(rows: list[dict[str, Any]]) -> str:
    for index, obj in enumerate(rows):
        validate_sgt(obj, index)
    blocks = [render_sgt(obj) for obj in rows]
    if not blocks:
        raise ReaderError("no SGTs to emit")
    return SGT_HEADER + "\n" + "\n\n".join(blocks) + "\n"


def write_policy_sets(root: Path) -> Path:
    text = render(load_policy_sets(root))
    path = root / WRITES[0]
    path.write_text(text, encoding="utf-8")
    return path


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Emit lab policy-set shells, rules, conditions, and allowed protocols from policy/."
    )
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument("--stdout", action="store_true", help="Print the file. Do not write it.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = args.root.resolve()
    try:
        sets = load_policy_sets(root)
        shells = render(sets)
        authn = render_authn(sets)
        authz = render_authz(sets)
        conditions = load_conditions(root)
        cnd_text = render_conditions(conditions)
        protocols = load_allowed_protocols(root)
        ap_text = render_allowed_protocols(protocols)
        dacls = load_dacls(root)
        dacl_text = render_dacls(dacls)
        vlan_map = load_vlan_map(root)
        profiles = load_profiles(root)
        profile_text = render_profiles(profiles, vlan_map)
        sgts = load_sgts(root)
        sgt_text = render_sgts(sgts)
    except ReaderError as exc:
        print(f"read_policy: {exc}", file=sys.stderr)
        return 1
    if args.stdout:
        sys.stdout.write(shells)
        sys.stdout.write("\n")
        sys.stdout.write(authn)
        sys.stdout.write("\n")
        sys.stdout.write(authz)
        sys.stdout.write("\n")
        sys.stdout.write(cnd_text)
        sys.stdout.write("\n")
        sys.stdout.write(ap_text)
        sys.stdout.write("\n")
        sys.stdout.write(dacl_text)
        sys.stdout.write("\n")
        sys.stdout.write(profile_text)
        sys.stdout.write("\n")
        sys.stdout.write(sgt_text)
        sys.stdout.write("\n")
        return 0
    written = []
    for rel, text in (
        (WRITES[0], shells),
        (WRITES[1], authn),
        (WRITES[2], authz),
        (WRITES[3], cnd_text),
        (WRITES[4], ap_text),
        (WRITES[5], dacl_text),
        (WRITES[6], profile_text),
        (WRITES[7], sgt_text),
    ):
        path = root / rel
        path.write_text(text, encoding="utf-8")
        written.append(rel)
    print("read_policy: wrote")
    for rel in written:
        print(f"- {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
