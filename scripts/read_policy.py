def load_vlan_map(root: Path) -> dict[str, str]:
    path = root / "inventory/vlans.yaml"
    if not path.is_file():
        raise ReaderError("inventory/vlans.yaml is missing")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(doc, dict):
        raise ReaderError("inventory/vlans.yaml is not a mapping")
    rows = doc.get("vlans")
    if not isinstance(rows, list):
        raise ReaderError("vlans must be a list")
    mapping: dict[str, str] = {}
    for index, row in enumerate(rows):
        if not isinstance(row, dict):
            raise ReaderError(f"vlan {index} is not a mapping")
        name = row.get("name")
        vlan_id = row.get("vlan_id")
        if not isinstance(name, str) or not name.startswith("VLAN-"):
            raise ReaderError(f"vlan {index} name must be VLAN- + kebab-case")
        if not isinstance(vlan_id, int) or vlan_id < 1:
            raise ReaderError(f"{name} vlan_id must be a positive integer")
        mapping[name] = str(vlan_id)
    return mapping


