def write_policy_sets(root: Path) -> Path:
    text = render(load_policy_sets(root))
    path = root / WRITES[0]
    path.write_text(text, encoding="utf-8")
    return path


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Emit lab policy-set shells, rules, conditions, and allowed protocols from policy/."
    )
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument("--stdout", action="store_true", help="Print the file. Do not write it.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = args.root.resolve()
    try:
        sets = load_policy_sets(root)
        shells = render(sets)
        authn = render_authn(sets)
        authz = render_authz(sets)
        conditions = load_conditions(root)
        cnd_text = render_conditions(conditions)
        protocols = load_allowed_protocols(root)
        ap_text = render_allowed_protocols(protocols)
        dacls = load_dacls(root)
        dacl_text = render_dacls(dacls)
        vlan_map = load_vlan_map(root)
        profiles = load_profiles(root)
        profile_text = render_profiles(profiles, vlan_map)
        sgts = load_sgts(root)
        sgt_text = render_sgts(sgts)
        eigs = load_eigs(root)
        eig_text = render_eigs(eigs)
        ndg_roots = load_ndg_roots(root)
        ndg_text = render_ndgs(ndg_roots)
        ndg_objects = derive_ndg_objects(ndg_roots)
        exceptions = load_exceptions(root)
        ex_text = render_exceptions(exceptions)
        outputs_text = render_outputs(
            sets, conditions, protocols, dacls, profiles, sgts, eigs, ndg_objects, exceptions
        )
    except ReaderError as exc:
        print(f"read_policy: {exc}", file=sys.stderr)
        return 1
    if args.stdout:
        sys.stdout.write(shells)
        sys.stdout.write("\n")
        sys.stdout.write(authn)
        sys.stdout.write("\n")
        sys.stdout.write(authz)
        sys.stdout.write("\n")
        sys.stdout.write(cnd_text)
        sys.stdout.write("\n")
        sys.stdout.write(ap_text)
        sys.stdout.write("\n")
        sys.stdout.write(dacl_text)
        sys.stdout.write("\n")
        sys.stdout.write(profile_text)
        sys.stdout.write("\n")
        sys.stdout.write(sgt_text)
        sys.stdout.write("\n")
        sys.stdout.write(eig_text)
        sys.stdout.write("\n")
        sys.stdout.write(ndg_text)
        sys.stdout.write("\n")
        sys.stdout.write(outputs_text)
        sys.stdout.write("\n")
        sys.stdout.write(ex_text)
        sys.stdout.write("\n")
        return 0
    written = []
    for rel, text in (
        (WRITES[0], shells),
        (WRITES[1], authn),
        (WRITES[2], authz),
        (WRITES[3], cnd_text),
        (WRITES[4], ap_text),
        (WRITES[5], dacl_text),
        (WRITES[6], profile_text),
        (WRITES[7], sgt_text),
        (WRITES[8], eig_text),
        (WRITES[9], ndg_text),
        (WRITES[10], outputs_text),
        (WRITES[11], ex_text),
    ):
        path = root / rel
        path.write_text(text, encoding="utf-8")
        written.append(rel)
    print("read_policy: wrote")
    for rel in written:
        print(f"- {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
