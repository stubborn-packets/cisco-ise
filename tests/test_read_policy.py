"""Reader emits the eight policy-set shells and nothing else."""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from read_policy import load_policy_sets, render, render_authn, render_authz  # noqa: E402  # type: ignore[import-not-found]


class ReadPolicySetShells(unittest.TestCase):
    def test_live_yaml_emits_eight_disabled_shells(self) -> None:
        text = render(load_policy_sets(REPO_ROOT))
        self.assertIn("Generated by scripts/read_policy.py", text)
        self.assertNotIn("for_each =", text)
        self.assertNotIn("band ", text)
        self.assertNotIn("authentication_rules", text)
        self.assertNotIn("authorization_rules", text)
        self.assertNotIn('state               = "enabled"', text)
        for label, rank in (
            ("ps_hr_wired", 0),
            ("ps_guest_wired", 1),
            ("ps_infra_health_checks", 2),
            ("ps_global_wireless_8021x", 3),
            ("ps_global_wireless_mab", 4),
            ("ps_global_vpn", 5),
            ("ps_global_wired_8021x", 6),
            ("ps_global_wired_mab", 7),
        ):
            self.assertIn(f'module "{label}"', text)
            self.assertIn(f"rank                = {rank}", text)
        self.assertIn("service_name        = module.ap_wired_mab.name", text)
        self.assertIn("condition_id        = module.cnd_vpn.id", text)
        self.assertIn("depends_on = [module.ap_vpn, module.cnd_vpn, module.ps_global_wireless_mab]", text)

    def test_live_yaml_emits_authentication_rules(self) -> None:
        text = render_authn(load_policy_sets(REPO_ROOT))
        self.assertIn("Generated by scripts/read_policy.py", text)
        self.assertNotIn("for_each =", text)
        self.assertNotIn("default ", text)
        self.assertNotIn("authorization_rules", text)
        for label, parent, identity in (
            ("an_hr_wired", "ps_hr_wired", "Internal Endpoints"),
            ("an_guest_wired", "ps_guest_wired", "Internal Endpoints"),
            ("an_infra_f5_health", "ps_infra_health_checks", "Internal Users"),
            ("an_wireless_dot1x", "ps_global_wireless_8021x", "Internal Users"),
            ("an_wireless_mab", "ps_global_wireless_mab", "Internal Endpoints"),
            ("an_vpn", "ps_global_vpn", "Internal Users"),
            ("an_wired_dot1x", "ps_global_wired_8021x", "Internal Users"),
            ("an_wired_mab", "ps_global_wired_mab", "Internal Endpoints"),
        ):
            self.assertIn(f'module "{label}"', text)
            self.assertIn(f"policy_set_id        = module.{parent}.id", text)
            self.assertIn(f'identity_source_name = "{identity}"', text)
        self.assertIn("condition_id         = module.cnd_wired_mab.id", text)
        self.assertIn('if_user_not_found    = "CONTINUE"', text)

    def test_repo_file_matches_render(self) -> None:
        path = REPO_ROOT / "environments" / "lab" / "policy-sets.tf"
        if not path.is_file():
            self.skipTest("generator has not been run")
        self.assertEqual(path.read_text(encoding="utf-8"), render(load_policy_sets(REPO_ROOT)))

    def test_authn_file_matches_render(self) -> None:
        path = REPO_ROOT / "environments" / "lab" / "authn-rules.tf"
        if not path.is_file():
            self.skipTest("generator has not been run")
        self.assertEqual(path.read_text(encoding="utf-8"), render_authn(load_policy_sets(REPO_ROOT)))

    def test_live_yaml_emits_authorization_rules(self) -> None:
        text = render_authz(load_policy_sets(REPO_ROOT))
        self.assertIn("Generated by scripts/read_policy.py", text)
        self.assertNotIn("for_each =", text)
        self.assertNotIn("security_group =", text)
        self.assertNotIn("PermitAccess", text)
        self.assertNotIn("default ", text)
        for label, parent, profile in (
            ("az_hr_wired", "ps_hr_wired", "PR-hr-wired-mab"),
            ("az_guest_wired", "ps_guest_wired", "PR-guest-wired-mab"),
            ("az_infra_f5_health", "ps_infra_health_checks", "PR-infra-permit"),
            ("az_wireless_dot1x", "ps_global_wireless_8021x", "PR-wired-lab-access"),
            ("az_wireless_mab", "ps_global_wireless_mab", "PR-wired-lab-access"),
            ("az_vpn", "ps_global_vpn", "PR-global-vpn"),
            ("az_wired_dot1x", "ps_global_wired_8021x", "PR-wired-lab-access"),
            ("az_wired_mab", "ps_global_wired_mab", "PR-wired-lab-access"),
        ):
            self.assertIn(f'module "{label}"', text)
            self.assertIn(f"policy_set_id       = module.{parent}.id", text)
            self.assertIn(f'profiles            = ["{profile}"]', text)
        self.assertIn("condition_id        = module.cnd_hr_eig.id", text)
        self.assertIn("depends_on = [module.ps_hr_wired, module.cnd_hr_eig, module.pr_hr_wired_mab]", text)

    def test_authz_file_matches_render(self) -> None:
        path = REPO_ROOT / "environments" / "lab" / "authz-rules.tf"
        if not path.is_file():
            self.skipTest("generator has not been run")
        self.assertEqual(path.read_text(encoding="utf-8"), render_authz(load_policy_sets(REPO_ROOT)))


if __name__ == "__main__":
    unittest.main()
